import json
C=[]
def P(n,e,c): C.append({"command":"parameters.add","params":{"name":n,"expression":e,"comment":c}})
def A(cmd,**p): C.append({"command":cmd,"params":p})
# ---- parameters
C.append({"command":"parameters.add","params":{"name":"tip_n","expression":"8","unit":"","comment":"Number of tips (grooves)"}})
P("tip_d","5 mm","T12 shaft diameter")
P("tip_len","157 mm","T12 overall length, connector end to working tip (bent tips included)")
P("ring_d","6 mm","Diameter of the two collars on the shaft")
P("ring_y1","86 mm","First collar position, from the connector end")
P("ring_y2","105.5 mm","Second collar position, from the connector end")
P("ring_w","4 mm","Collar pocket length (generous: collar positions vary between makers)")
P("clear","0.45 mm","Radial clearance round the shaft and collars")
P("groove_d","tip_d + 2*clear","Tip groove diameter")
P("ring_pd","ring_d + 2*clear","Collar pocket diameter")
P("pitch","7.4 mm","Groove spacing (X)")
P("edge_m","1 mm","Extra side room between the outer grooves and the side walls")
P("end_clear","2 mm","Room at each end of the tip")
P("tip_zone","25 mm","Working-end zone: open trough to the floor so bent tips (e.g. JL02) fit")
P("bend_h","4 mm","Room for a bent tip from the shaft axis, up and down")
P("wall","4 mm","Wall thickness (side walls carry the lid dovetail)")
P("base_t","1.6 mm","Floor thickness under the tip zone")
P("corner_r","3 mm","Outer vertical corner radius")
P("foot_ch","0.6 mm","45 deg chamfer round the box bottom edge (against elephant foot)")
P("top_ch","0.8 mm","45 deg chamfer round the box top outer edge and the front wall top")
P("lid_ch","0.5 mm","45 deg chamfer on the lid's front and back top edges (the lid's bed side)")
P("lid_t","2.5 mm","Lid thickness")
P("lid_land","0.8 mm","Vertical land at the lid's long bottom edges before the 45 deg bevel (no knife edge)")
P("lid_recess","1 mm","Lid top sits this far below the box top")
P("lip_ch","0.5 mm","45 deg chamfer on the wall's inner top edge above the lid")
P("dov","2 mm","Dovetail: how far the lid's lower edge reaches into each side wall")
P("lid_c","0.3 mm","Lid sliding clearance")
P("lid_engage","1 mm","Lid end tucks this far into the back wall")

P("tongue_l","22 mm","Click tongue length")
P("slot_w","1.2 mm","Width of the slots either side of the tongue")
P("click_r","0.6 mm","Click bump radius (under the tongue)")
P("click_notch_r","click_r + 0.15 mm","Click notch radius in the front wall top")
P("ramp","1 mm","45 deg ramp on the front wall's inner top edge, lets the bump ride up")
P("scoop_r","8 mm","Finger scoop radius across the bed")
P("scoop_d","3 mm","Finger scoop depth below the bed top")
P("scoop_y","35 mm","Finger scoop position from the connector end")
# derived
P("Wi","tip_n*pitch + 2*edge_m","Inner width")
P("Li","tip_len + 2*end_clear","Inner length")
P("W","Wi + 2*wall","Outer width (X)")
P("L","Li + 2*wall","Outer length (Y)")
P("z_axis","base_t + bend_h","Height of the tip axes = bed top")
P("z_lid","z_axis + max(bend_h, ring_pd/2) + 0.5 mm","Lid underside")
P("H","z_lid + lid_t + lid_recess","Overall height (lid top lid_recess below the wall tops)")
P("x0","wall + edge_m + pitch/2","X of the first groove")
P("y0","wall + end_clear","Y of the tip connector end")
P("tongue_w","min(16 mm, Wi/2)","Click tongue width (flexible strip at the lid front), at most half the inner width")
# ---- box
A("sketch.create",name="Sk_Outline_Foot",plane="XY")
A("sketch.rectangle.rounded",p0=["foot_ch","foot_ch"],p1=["W - foot_ch","L - foot_ch"],radius="corner_r - foot_ch")
A("sketch.finish")
A("solid.extrude",name="Box_Foot_Chamfer",sketch="Sk_Outline_Foot",distance="foot_ch",taper="45 deg",profiles="all",operation="new",body_name="Tip_Box")
A("sketch.create",name="Sk_Outline",plane="XY",offset="foot_ch")
A("sketch.rectangle.rounded",p0=[0,0],p1=["W","L"],radius="corner_r")
A("sketch.finish")
A("solid.extrude",name="Box_Block",sketch="Sk_Outline",distance="H - foot_ch - top_ch",profiles="all",operation="join",targets=["Tip_Box"])
A("sketch.create",name="Sk_Outline_Top",plane="XY",offset="H - top_ch")
A("sketch.rectangle.rounded",p0=[0,0],p1=["W","L"],radius="corner_r")
A("sketch.finish")
A("solid.extrude",name="Box_Top_Chamfer",sketch="Sk_Outline_Top",distance="top_ch",taper="-45 deg",profiles="all",operation="join",targets=["Tip_Box"])
A("solid.box",name="Cavity",length="Wi",width="Li",height="H",corner=["wall","wall","base_t"],operation="cut",targets=["Tip_Box"])
A("solid.box",name="Bed",length="Wi + 1 mm",width="Li - tip_zone + 0.5 mm",height="z_axis - base_t + 0.5 mm",corner=["wall - 0.5 mm","wall - 0.5 mm","base_t - 0.5 mm"],operation="join",targets=["Tip_Box"])
A("solid.cylinder",name="Groove",radius="groove_d/2",height="Li - tip_zone - end_clear/2 + 1 mm",base=["x0","wall + end_clear/2","z_axis"],axis="Y",operation="cut",targets=["Tip_Box"])
A("solid.cylinder",name="Ring_Pocket1",radius="ring_pd/2",height="ring_w",base=["x0","y0 + ring_y1 - ring_w/2","z_axis"],axis="Y",operation="cut",targets=["Tip_Box"])
A("solid.cylinder",name="Ring_Pocket2",radius="ring_pd/2",height="ring_w",base=["x0","y0 + ring_y2 - ring_w/2","z_axis"],axis="Y",operation="cut",targets=["Tip_Box"])
A("solid.pattern.rectangular",name="Groove_Pattern",features=["Groove","Ring_Pocket1","Ring_Pocket2"],dir1=[1,0,0],count1="tip_n",spacing1="pitch")
A("solid.cylinder",name="Finger_Scoop",radius="scoop_r",height="Wi - 1 mm",base=["wall + 0.5 mm","y0 + scoop_y","z_axis + scoop_r - scoop_d"],axis="X",operation="cut",targets=["Tip_Box"])
# dovetail way: one trapezoid across the whole width, front to back wall (+engage)
A("sketch.create",name="Sk_Dovetail",plane={"origin":[0,-1,0],"x_dir":[1,0,0],"y_dir":[0,0,1]})
A("sketch.line",closed=True,points=[
 ["wall - dov - lid_c","z_lid"],["W - wall + dov + lid_c","z_lid"],
 ["W - wall + dov + lid_c","z_lid + lid_land"],
 ["W - wall + dov - lid_t + lid_land","z_lid + lid_t + lid_c"],
 ["W - wall + dov - lid_t + lid_land","H - lip_ch"],
 ["W - wall + dov - lid_t + lid_land + lip_ch + 1 mm","H + 1 mm"],
 ["wall - dov + lid_t - lid_land - lip_ch - 1 mm","H + 1 mm"],
 ["wall - dov + lid_t - lid_land","H - lip_ch"],
 ["wall - dov + lid_t - lid_land","z_lid + lid_t + lid_c"],
 ["wall - dov - lid_c","z_lid + lid_land"]])
A("sketch.finish")
A("solid.extrude",name="Dovetail_Way",sketch="Sk_Dovetail",distance="L - wall + lid_engage + 1 mm",direction="negative",profiles="all",operation="cut",targets=["Tip_Box"])
A("solid.box",name="Front_Opening",length="Wi",width="wall + 1.5 mm",height="H",corner=["wall",-1,"z_lid"],operation="cut",targets=["Tip_Box"])
A("sketch.create",name="Sk_Ramp",plane="YZ",offset="W/2 - tongue_w/2")
A("sketch.line",closed=True,points=[["wall - ramp - 0.5 mm","z_lid + 0.5 mm"],["wall + 0.5 mm","z_lid + 0.5 mm"],["wall + 0.5 mm","z_lid - ramp - 0.5 mm"]])
A("sketch.finish")
A("solid.extrude",name="Click_Ramp",sketch="Sk_Ramp",distance="tongue_w",profiles="all",operation="cut",targets=["Tip_Box"])
A("solid.cylinder",name="Click_Notch",radius="click_notch_r",height="tongue_w - 2 mm",base=["W/2 - tongue_w/2 + 1 mm","wall/2","z_lid"],axis="X",operation="cut",targets=["Tip_Box"])
A("sketch.create",name="Sk_Front_Ch",plane="YZ",offset="wall - dov - lid_c + 0.3 mm")
A("sketch.line",closed=True,points=[["-0.5 mm","z_lid - top_ch - 0.5 mm"],["top_ch + 0.5 mm","z_lid + 0.5 mm"],["-0.5 mm","z_lid + 0.5 mm"]])
A("sketch.finish")
A("solid.extrude",name="Front_Edge_Chamfer",sketch="Sk_Front_Ch",distance="Wi + 2*(dov + lid_c) - 0.6 mm",profiles="all",operation="cut",targets=["Tip_Box"])
# ---- lid
A("sketch.create",name="Sk_Lid",plane={"origin":[0,0,0],"x_dir":[1,0,0],"y_dir":[0,0,1]})
A("sketch.line",closed=True,points=[["wall - dov","z_lid"],["W - wall + dov","z_lid"],["W - wall + dov","z_lid + lid_land"],["W - wall + dov - lid_t + lid_land","z_lid + lid_t"],["wall - dov + lid_t - lid_land","z_lid + lid_t"],["wall - dov","z_lid + lid_land"]])
A("sketch.finish")
A("solid.extrude",name="Lid_Plate",sketch="Sk_Lid",distance="L - wall + lid_engage - lid_c",direction="negative",profiles="all",operation="new",body_name="Lid")
A("solid.box",name="Tongue_Slot_L",length="slot_w",width="tongue_l + 1 mm",height="lid_t + 2 mm",corner=["W/2 - tongue_w/2 - slot_w",-1,"z_lid - 1 mm"],operation="cut",targets=["Lid"])
A("solid.box",name="Tongue_Slot_R",length="slot_w",width="tongue_l + 1 mm",height="lid_t + 2 mm",corner=["W/2 + tongue_w/2",-1,"z_lid - 1 mm"],operation="cut",targets=["Lid"])
A("solid.cylinder",name="Tongue_Root_L",radius="slot_w/2",height="lid_t + 2 mm",base=["W/2 - tongue_w/2 - slot_w/2","tongue_l","z_lid - 1 mm"],operation="cut",targets=["Lid"])
A("solid.cylinder",name="Tongue_Root_R",radius="slot_w/2",height="lid_t + 2 mm",base=["W/2 + tongue_w/2 + slot_w/2","tongue_l","z_lid - 1 mm"],operation="cut",targets=["Lid"])
A("sketch.create",name="Sk_Lid_Ch",plane="YZ",offset="-1 mm")
A("sketch.line",closed=True,points=[["-0.5 mm","z_lid + lid_t - lid_ch - 0.5 mm"],["lid_ch + 0.5 mm","z_lid + lid_t + 0.5 mm"],["-0.5 mm","z_lid + lid_t + 0.5 mm"]])
A("sketch.line",closed=True,points=[["L - wall + lid_engage - lid_c + 0.5 mm","z_lid + lid_t - lid_ch - 0.5 mm"],["L - wall + lid_engage - lid_c + 0.5 mm","z_lid + lid_t + 0.5 mm"],["L - wall + lid_engage - lid_c - lid_ch - 0.5 mm","z_lid + lid_t + 0.5 mm"]])
A("sketch.finish")
A("solid.extrude",name="Lid_End_Chamfers",sketch="Sk_Lid_Ch",distance="W + 2 mm",profiles="all",operation="cut",targets=["Lid"])
A("solid.cylinder",name="Click_Bump",radius="click_r",height="tongue_w - 4 mm",base=["W/2 - tongue_w/2 + 2 mm","wall/2","z_lid"],axis="X",operation="join",targets=["Lid"])
A("appearance.assign",bodies=["Tip_Box"],color="#d9d9d9")
